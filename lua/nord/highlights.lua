-- the variants in nord.palette). Deliberately covers only: core editor UI,
-- base syntax groups, Treesitter @captures, and LSP diagnostics/semantic
-- tokens -- no per-plugin groups. Most plugins (telescope, cmp, gitsigns,
-- lualine, ...) read these same base/treesitter/LSP groups already, so
