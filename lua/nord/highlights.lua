-- Builds the full highlight-group table for a given color table (one of
-- the variants in nord.palette). Deliberately covers only: core editor UI,
-- base syntax groups, Treesitter @captures, and LSP diagnostics/semantic
-- tokens -- no per-plugin groups. Most plugins (telescope, cmp, gitsigns,
-- lualine, ...) read these same base/treesitter/LSP groups already, so
-- they inherit a consistent look for free via Neovim's highlight-link
-- fallback instead of needing bespoke entries here.
local M = {}

function M.build(c)
  return {
    -- Editor UI
    Normal = { fg = c.fg, bg = c.bg },
    NormalFloat = { fg = c.fg, bg = c.float },
    FloatBorder = { fg = c.blue, bg = c.float },
    ColorColumn = { bg = c.float },
    Cursor = { reverse = true },
    CursorLine = { bg = c.active },
    CursorLineNr = { fg = c.fg, bold = true },
    LineNr = { fg = c.light_gray },
    SignColumn = { fg = c.fg, bg = c.bg },
    VertSplit = { fg = c.highlight_dark },
    WinSeparator = { fg = c.highlight_dark },
    Visual = { bg = c.highlight },
    Search = { fg = c.bg, bg = c.yellow },
    IncSearch = { fg = c.bg, bg = c.orange },
    CurSearch = { fg = c.bg, bg = c.orange },
    Pmenu = { fg = c.fg, bg = c.float },
    PmenuSel = { bg = c.selection },
    PmenuSbar = { bg = c.float },
    PmenuThumb = { bg = c.highlight_dark },
    StatusLine = { fg = c.fg, bg = c.active },
    StatusLineNC = { fg = c.light_gray, bg = c.active },
    TabLine = { fg = c.light_gray, bg = c.active },
    TabLineSel = { fg = c.fg, bg = c.bg },
    TabLineFill = { bg = c.active },
    Directory = { fg = c.blue },
    Title = { fg = c.green, bold = true },
    MatchParen = { fg = c.yellow, bold = true },
    NonText = { fg = c.gray },
    Whitespace = { fg = c.gray },
    EndOfBuffer = { fg = c.gray },
    FoldColumn = { fg = c.light_gray },
    Folded = { fg = c.dark_blue, italic = true },
    WildMenu = { fg = c.bg, bg = c.yellow },
    ModeMsg = { fg = c.blue, bold = true },
    MoreMsg = { fg = c.blue, bold = true },
    Question = { fg = c.green },
    ErrorMsg = { fg = c.error },
    WarningMsg = { fg = c.warn },

    -- Base syntax
    Comment = { fg = c.light_gray, italic = true },
    String = { fg = c.cyan },
    Character = { fg = c.green },
    Number = { fg = c.orange },
    Boolean = { fg = c.orange },
    Float = { fg = c.orange },
    Constant = { fg = c.blue },
    Identifier = { fg = c.fg },
    Function = { fg = c.blue },
    Statement = { fg = c.purple },
    Conditional = { fg = c.purple },
    Repeat = { fg = c.purple },
    Label = { fg = c.purple },
    Operator = { fg = c.purple },
    Keyword = { fg = c.purple },
    Exception = { fg = c.purple },
    PreProc = { fg = c.purple },
    Include = { fg = c.blue },
    Define = { fg = c.purple },
    Macro = { fg = c.red },
    Typedef = { fg = c.purple },
    Type = { fg = c.yellow },
    StorageClass = { fg = c.purple },
    Structure = { fg = c.purple },
    Special = { fg = c.light_red },
    SpecialChar = { fg = c.light_red },
    Tag = { fg = c.green },
    Delimiter = { fg = c.dark_blue },
    Underlined = { fg = c.green, underline = true },
    Error = { fg = c.error, bold = true },
    Todo = { fg = c.yellow, bold = true },

    -- Diff
    DiffAdd = { bg = c.diff_add_bg },
    DiffChange = { bg = c.diff_change_bg },
    DiffDelete = { bg = c.diff_remove_bg },
    DiffText = { bg = c.diff_text_bg },

    -- Spell
    SpellBad = { undercurl = true, sp = c.error },
    SpellCap = { undercurl = true, sp = c.warn },
    SpellLocal = { undercurl = true, sp = c.cyan },
    SpellRare = { undercurl = true, sp = c.purple },

    -- Treesitter captures. Deliberately NOT all linked to the base syntax
    -- groups above: mynord.nvim used a richer, distinct palette here (e.g.
    -- strings were green even though legacy `String` was cyan, functions
    -- were cyan even though legacy `Function` was blue). Keep that split —
    -- treesitter is what you actually see day to day.
    ["@variable"] = { fg = c.fg },
    ["@variable.builtin"] = { fg = c.fg },
    ["@variable.parameter"] = { fg = c.fg },
    ["@variable.member"] = { fg = c.fg },
    ["@constant"] = { fg = c.fg },
    ["@constant.builtin"] = { fg = c.fg_light },
    ["@constant.macro"] = { fg = c.red },
    ["@module"] = { fg = c.blue },
    ["@string"] = { fg = c.green },
    ["@string.escape"] = { fg = c.orange },
    ["@string.regex"] = { fg = c.orange },
    ["@character"] = { fg = c.green },
    ["@number"] = { fg = c.orange },
    ["@number.float"] = { fg = c.orange },
    ["@boolean"] = { fg = c.dark_blue },
    ["@function"] = { fg = c.cyan },
    ["@function.builtin"] = { fg = c.cyan },
    ["@function.macro"] = { fg = c.cyan },
    ["@function.method"] = { fg = c.cyan },
    ["@constructor"] = { fg = c.cyan },
    ["@keyword"] = { fg = c.purple },
    ["@keyword.function"] = { fg = c.purple },
    ["@keyword.return"] = { fg = c.purple },
    ["@keyword.operator"] = { fg = c.purple },
    ["@keyword.import"] = { fg = c.purple },
    ["@keyword.conditional"] = { fg = c.purple },
    ["@keyword.repeat"] = { fg = c.purple },
    ["@keyword.exception"] = { fg = c.purple },
    ["@conditional"] = { fg = c.purple },
    ["@repeat"] = { fg = c.purple },
    ["@label"] = { fg = c.purple },
    ["@operator"] = { fg = c.purple },
    ["@punctuation.delimiter"] = { fg = c.dark_blue },
    ["@punctuation.bracket"] = { fg = c.dark_blue },
    ["@punctuation.special"] = { fg = c.dark_blue },
    ["@comment"] = { fg = c.gray, italic = true },
    ["@comment.note"] = { fg = c.green, bold = true },
    ["@comment.warning"] = { fg = c.yellow, bold = true },
    ["@comment.error"] = { fg = c.red, bold = true },
    ["@type"] = { fg = c.light_green },
    ["@type.builtin"] = { fg = c.light_green },
    ["@attribute"] = { fg = c.orange },
    ["@property"] = { fg = c.fg },
    ["@tag"] = { fg = c.blue },
    ["@tag.attribute"] = { fg = c.fg_light },
    ["@tag.delimiter"] = { fg = c.dark_blue },
    ["@error"] = { fg = c.error },
    ["@markup.strong"] = { fg = c.purple, bold = true },
    ["@markup.italic"] = { fg = c.yellow, italic = true },
    ["@markup.underline"] = { underline = true },
    ["@markup.heading"] = { fg = c.blue, bold = true },
    ["@markup.link.url"] = { fg = c.cyan, underline = true },
    ["@markup.raw"] = { fg = c.green },
    ["@markup.list"] = { fg = c.purple },
    ["@markup.list.checked"] = { fg = c.green },
    ["@markup.list.unchecked"] = { fg = c.dark_blue },

    -- LSP diagnostics + semantic tokens
    DiagnosticError = { fg = c.error },
    DiagnosticWarn = { fg = c.warn },
    DiagnosticInfo = { fg = c.info },
    DiagnosticHint = { fg = c.hint },
    DiagnosticUnderlineError = { undercurl = true, sp = c.error },
    DiagnosticUnderlineWarn = { undercurl = true, sp = c.warn },
    DiagnosticUnderlineInfo = { undercurl = true, sp = c.info },
    DiagnosticUnderlineHint = { undercurl = true, sp = c.hint },
    LspReferenceText = { bg = c.selection },
    LspReferenceRead = { bg = c.selection },
    LspReferenceWrite = { bg = c.selection },
    -- Linked to the matching Treesitter capture above rather than given
    -- their own fg, so there is exactly one color definition per concept —
    -- whichever one Neovim's LSP-vs-Treesitter priority picks at a given
    -- token, it resolves to the same place. The one exception is
    -- @lsp.type.struct: there's no Treesitter capture for "struct" as a
    -- distinct concept (grammars fold it into @type), and mynord.nvim
    -- deliberately colored it differently (purple, not @type's
    -- light_green), so it stays its own explicit color.
    ["@lsp.type.namespace"] = { link = "@module" },
    ["@lsp.type.class"] = { link = "@type" },
    ["@lsp.type.interface"] = { link = "@type" },
    ["@lsp.type.enum"] = { link = "@type" },
    ["@lsp.type.enumMember"] = { link = "@variable.member" },
    ["@lsp.type.struct"] = { fg = c.purple },
    ["@lsp.type.parameter"] = { link = "@variable.parameter" },
    ["@lsp.type.property"] = { link = "@property" },
    ["@lsp.type.variable"] = { link = "@variable" },
    ["@lsp.type.function"] = { link = "@function" },
    ["@lsp.type.method"] = { link = "@function.method" },
    ["@lsp.type.macro"] = { link = "@function.macro" },
    ["@lsp.type.decorator"] = { link = "@function" },
  }
end

return M
